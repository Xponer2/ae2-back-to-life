package appeng.client.render.effects;

import net.minecraft.client.particle.Particle;
import net.minecraft.util.EnumFacing;
import net.minecraft.world.World;
import net.minecraftforge.fml.relauncher.Side;
import net.minecraftforge.fml.relauncher.SideOnly;

@SideOnly(Side.CLIENT)
public class MatterCannonFX extends AEParticle {

    public MatterCannonFX(World level, double x, double y, double z) {
        super(level, x, y, z);
        this.particleGravity = 0;
        this.particleBlue = 1;
        this.particleGreen = 1;
        this.particleRed = 1;
        this.particleAlpha = 1.4f;
        this.particleScale = 1.1f;
        this.motionX = 0.0f;
        this.motionY = 0.0f;
        this.motionZ = 0.0f;
        this.setSprite(AEParticles.getMatterCannonSprite());
    }

    public void fromItem(EnumFacing d) {
        this.particleScale *= 1.2f;
    }

    @Override
    public void onUpdate() {
        this.prevPosX = this.posX;
        this.prevPosY = this.posY;
        this.prevPosZ = this.posZ;

        if (this.particleAge++ >= this.particleMaxAge) {
            this.setExpired();
        }

        this.motionY -= 0.04D * this.particleGravity;
        this.move(this.motionX, this.motionY, this.motionZ);
        this.motionX *= 0.9800000190734863D;
        this.motionY *= 0.9800000190734863D;
        this.motionZ *= 0.9800000190734863D;

        this.particleScale *= 1.19f;
        this.particleAlpha *= 0.59f;
    }

    @SideOnly(Side.CLIENT)
    public static final class Factory {
        private Factory() {
        }

        public static Particle createParticle(SimpleParticleType data, World level, double x, double y, double z,
                double xSpeed, double ySpeed, double zSpeed) {
            return new MatterCannonFX(level, x, y, z);
        }
    }
}
