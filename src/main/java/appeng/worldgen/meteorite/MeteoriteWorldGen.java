package appeng.worldgen.meteorite;

import java.util.Random;

import net.minecraft.util.math.ChunkPos;
import net.minecraft.world.World;
import net.minecraft.world.WorldServer;
import net.minecraft.world.chunk.IChunkProvider;
import net.minecraft.world.gen.IChunkGenerator;
import net.minecraft.world.gen.structure.StructureBoundingBox;
import net.minecraftforge.fml.common.IWorldGenerator;

import appeng.hooks.ticking.TickHandler;
import appeng.server.services.compass.ServerCompassService;

/**
 * Generates the meteorites (1.12.2 replacement for the 1.21 structure). When a chunk has been populated:
 * <ul>
 * <li>if it is the start chunk of a meteorite ({@link MeteoriteStructure}), the meteorite is decided and placed in it
 * and in the already populated chunks of its area that are loaded;</li>
 * <li>if it lies in the area of an already decided meteorite, the part of the meteorite in this chunk is placed.</li>
 * </ul>
 * Blocks are only written into the chunk being handled, and the work is done in the next server tick (not during the
 * population), so no chunk is generated by it.
 */
public final class MeteoriteWorldGen implements IWorldGenerator {

    @Override
    public void generate(Random random, int chunkX, int chunkZ, World world, IChunkGenerator chunkGenerator,
            IChunkProvider chunkProvider) {
        if (!(world instanceof WorldServer level) || !MeteoriteStructure.isAllowedDimension(world)) {
            return;
        }
        var chunk = new ChunkPos(chunkX, chunkZ);
        // Quick check without touching the saved data
        if (MeteoriteStructure.getPotentialStartsAround(world.getSeed(), chunk).isEmpty()) {
            return;
        }
        TickHandler.instance().addCallable(world, () -> onChunkPopulated(level, chunk));
    }

    private static void onChunkPopulated(WorldServer level, ChunkPos chunk) {
        var data = MeteoriteSpawnData.get(level);
        for (var start : MeteoriteStructure.getPotentialStartsAround(level.getSeed(), chunk)) {
            var entry = data.get(start);
            if (entry == null) {
                if (!start.equals(chunk)) {
                    // Decided once the start chunk is populated
                    continue;
                }
                entry = data.add(start, MeteoriteStructure.createSettings(level, start));
                if (entry.getSettings() != null) {
                    placeInPopulatedNeighbors(level, data, entry);
                }
            }
            if (entry.getSettings() != null) {
                placeInChunk(level, data, entry, chunk);
            }
        }
    }

    private static void placeInPopulatedNeighbors(WorldServer level, MeteoriteSpawnData data,
            MeteoriteSpawnData.Entry entry) {
        var start = entry.getStart();
        int range = MeteoriteStructure.RANGE_CHUNKS;
        for (int x = start.x - range; x <= start.x + range; x++) {
            for (int z = start.z - range; z <= start.z + range; z++) {
                var neighbor = level.getChunkProvider().getLoadedChunk(x, z);
                if (neighbor != null && neighbor.isTerrainPopulated()) {
                    placeInChunk(level, data, entry, new ChunkPos(x, z));
                }
            }
        }
    }

    private static void placeInChunk(WorldServer level, MeteoriteSpawnData data, MeteoriteSpawnData.Entry entry,
            ChunkPos chunk) {
        if (entry.isPlaced(chunk)) {
            return;
        }
        var start = entry.getStart();
        int range = MeteoriteStructure.RANGE_CHUNKS;
        if (Math.abs(chunk.x - start.x) > range || Math.abs(chunk.z - start.z) > range) {
            return;
        }
        var boundingBox = new StructureBoundingBox(chunk.getXStart(), 0, chunk.getZStart(), chunk.getXEnd(),
                level.getHeight() - 1, chunk.getZEnd());
        var random = new Random(level.getSeed() + chunk.x * 341873128712L + chunk.z * 132897987541L);
        MeteoritePlacer.place(level, entry.getSettings(), boundingBox, random);
        data.markPlaced(entry, chunk);

        ServerCompassService.updateArea(level, level.getChunk(chunk.x, chunk.z));
    }
}
